export function createI18n(initialLocale = "zh-CN") {
  const state = reactive({
    locale: messages[initialLocale] ? initialLocale : "zh-CN",
  });

  function setLocale(locale) {
    if (messages[locale]) state.locale = locale;
  }

  function t(key, params) {
    const raw = messages[state.locale]?.[key] || messages["zh-CN"]?.[key] || key;
    if (!params || typeof raw !== "string") return raw;
    return raw.replace(/\{(\w+)\}/g, (_, name) => String(params?.[name] ?? ""));
  }

  return {
    state,
    locales: [
      { value: "zh-CN", label: "简体中文" },
      { value: "en-US", label: "English" },
    ],
    setLocale,
    t,
  };
}

export function useI18n() {
  const i18n = inject(I18N_KEY, null);
  if (!i18n) {
    throw new Error("NodeWall i18n provider is missing");
  }
  return {
    ...i18n,
    locale: computed(() => i18n.state.locale),
  };
}
